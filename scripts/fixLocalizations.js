const fs = require('fs');
const path = require('path');

module.exports = function (context) {
    console.log('[LocalizationHook] Starting pre-compile localization verification...');

    const projectRoot = context.opts.projectRoot;
    const iosPlatformPath = path.join(projectRoot, 'platforms', 'ios');

    if (!fs.existsSync(iosPlatformPath)) {
        console.warn('[LocalizationHook] platforms/ios not found. Skipping.');
        return;
    }

    // Locate the iOS project directory containing *-Info.plist
    const entries = fs.readdirSync(iosPlatformPath, { withFileTypes: true });
    const projectDir = entries.find(entry =>
        entry.isDirectory() &&
        fs.existsSync(path.join(iosPlatformPath, entry.name, `${entry.name}-Info.plist`))
    );

    if (!projectDir) {
        console.warn('[LocalizationHook] Target Xcode app directory not found.');
        return;
    }

    const appDir = path.join(iosPlatformPath, projectDir.name);
    console.log(`[LocalizationHook] Target App Directory: ${appDir}`);

    // Resolve plugin directory reliably across Cordova and MABS versions
    let pluginDir = (context.opts.plugin && context.opts.plugin.dir)
        ? context.opts.plugin.dir
        : path.join(projectRoot, 'plugins', 'cordova-custom-config');

    if (!fs.existsSync(pluginDir)) {
        const pluginsRoot = path.join(projectRoot, 'plugins');
        if (fs.existsSync(pluginsRoot)) {
            const match = fs.readdirSync(pluginsRoot).find(p =>
                fs.existsSync(path.join(pluginsRoot, p, 'Localisation'))
            );
            if (match) {
                pluginDir = path.join(pluginsRoot, match);
            }
        }
    }
    console.log(`[LocalizationHook] Source Plugin Directory: ${pluginDir}`);

    const languages = ['en', 'ar'];

    // Ensure .lproj folders and InfoPlist.strings exist physically in the app bundle
    languages.forEach(lang => {
        const destLangDir = path.join(appDir, `${lang}.lproj`);
        if (!fs.existsSync(destLangDir)) {
            fs.mkdirSync(destLangDir, { recursive: true });
            console.log(`[LocalizationHook] Created directory: ${destLangDir}`);
        }

        const srcFile = path.join(pluginDir, 'Localisation', `${lang}.lproj`, 'InfoPlist.strings');
        const destFile = path.join(destLangDir, 'InfoPlist.strings');

        if (fs.existsSync(srcFile)) {
            fs.copyFileSync(srcFile, destFile);
            console.log(`[LocalizationHook] Copied ${srcFile} -> ${destFile}`);
        } else if (!fs.existsSync(destFile)) {
            // Fallback generation if source path could not be resolved
            console.warn(`[LocalizationHook] Source file missing at ${srcFile}. Creating fallback at ${destFile}`);
            fs.writeFileSync(destFile, '/* Generated by fixLocalizations hook */\n', 'utf8');
        }
    });

    // Enforce CFBundleLocalizations in *-Info.plist
    const plistPath = path.join(appDir, `${projectDir.name}-Info.plist`);
    if (fs.existsSync(plistPath)) {
        let content = fs.readFileSync(plistPath, 'utf8');
        const regex = /<key>CFBundleLocalizations<\/key>[\s\S]*?<\/array>/;
        const replacement = `<key>CFBundleLocalizations</key>\n\t<array>\n\t\t<string>en</string>\n\t\t<string>ar</string>\n\t</array>`;

        if (regex.test(content)) {
            content = content.replace(regex, replacement);
        } else {
            content = content.replace('</dict>', `\t${replacement}\n</dict>`);
        }

        fs.writeFileSync(plistPath, content, 'utf8');
        console.log('[LocalizationHook] Successfully enforced CFBundleLocalizations [en, ar] in Info.plist.');
    }
};
